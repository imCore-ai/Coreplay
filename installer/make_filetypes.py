"""Writes installer/filetypes.nsh: the file types the Coreplay installer registers.

One list per group, so install and uninstall code always agree. Groups that are off by
default leave the user's image viewer / music player alone; every type still lists
Coreplay under "Open with".
Run: python -I installer/make_filetypes.py
"""
import os

GROUPS = [
    # id, label, ProgID, on by default, extensions
    ("Video", "Video files", "Coreplay.Video", True,
     "mp4 m4v mov qt mkv webm avi wmv asf flv mxf mts m2ts ts mpg mpeg m2v vob 3gp ogv dv y4m "
     "r3d braw hevc h264 h265 264 265 ivf nut rm rmvb"),
    ("Sequence", "Image sequences: EXR, DPX, Cineon, HDR", "Coreplay.Sequence", True,
     "exr dpx cin hdr sgi rgb iff tx"),
    ("Playlist", "Playlists (M3U, M3U8)", "Coreplay.Playlist", True, "m3u m3u8"),
    ("Audio", "Audio files", "Coreplay.Audio", False,
     "mp3 wav flac aac m4a ogg opus wma aiff aif ac3 eac3 dts mka"),
    ("Image", "Common images: PNG, JPEG, TIFF, TGA, WebP...", "Coreplay.Image", False,
     "png jpg jpeg tif tiff tga bmp webp jp2 j2k psd gif"),
]


def main():
    out = ["; Generated by installer/make_filetypes.py - do not edit by hand.", ""]
    for gid, label, progid, on, exts in GROUPS:
        exts = exts.split()
        out.append(f'!macro Register{gid} ; every type lists Coreplay under "Open with"')
        out += [f'  !insertmacro RegisterType "{e}" "{progid}"' for e in exts]
        out.append("!macroend")
        out.append(f"!macro Default{gid}")
        out += [f'  !insertmacro MakeDefault "{e}" "{progid}"' for e in exts]
        out.append("!macroend")
        out.append(f"!macro Unregister{gid}")
        out += [f'  !insertmacro UnregisterType "{e}" "{progid}"' for e in exts]
        out.append("!macroend")
        out.append(f'!define LABEL_{gid} "{label}"')
        out.append(f'!define PROGID_{gid} "{progid}"')
        out.append(f'!define ON_{gid} {"1" if on else "0"}')
        out.append("")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "filetypes.nsh")
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path, sum(len(g[4].split()) for g in GROUPS), "types")


if __name__ == "__main__":
    main()
